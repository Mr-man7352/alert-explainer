"""Day 5 write-up: LightGBM vs PyTorch comparison table and model cards. ``uv run ae compare``.

Reads ``reports/lgbm_metrics.json``, ``reports/mlp_metrics.json`` and (if present)
``reports/cross_day.json``. Writes ``reports/model_comparison.md`` / ``.json`` and
``models/{lgbm,mlp}/model_card.md`` (the cards are committed; the weights are not).
Every number is copied from the metrics files, so the documents can be regenerated after any re-run.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def _load(path: Path) -> dict[str, Any] | None:
    return json.loads(path.read_text()) if path.exists() else None


def _f(value: Any, digits: int = 4) -> str:
    if value is None:
        return "–"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    if isinstance(value, int):
        return f"{value:,}"
    return str(value)


def _pct(value: Any, digits: int = 2) -> str:
    return "–" if value is None else f"{value:.{digits}%}"


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def _size(m: dict[str, Any]) -> str:
    if m["model"] == "lightgbm":
        return f"{m['best_iteration']} rounds × {len(m['classes'])} trees"
    return f"{m['n_parameters']:,} parameters"


def _macro_pr_auc(m: dict[str, Any]) -> float | None:
    values = [
        v["pr_auc"]
        for v in m["test_at_threshold"]["per_family"].values()
        if v["pr_auc"] is not None
    ]
    return sum(values) / len(values) if values else None


def comparison_markdown(
    lgbm: dict[str, Any], mlp: dict[str, Any], cross_day: dict[str, Any] | None
) -> str:
    models = {"LightGBM": lgbm, "PyTorch MLP": mlp}
    parts = [
        "# Detection: LightGBM vs PyTorch MLP",
        "",
        "Generated by `uv run ae compare` from `reports/*_metrics.json`. Test set: stratified 15% "
        "of de-duplicated CIC-IDS2017 (same rows for both models). Both use the same decision rule, "
        "threshold rule (BENIGN FPR ≤ "
        f"{lgbm['target_benign_fpr']:.0%} on validation, lowest threshold within 0.003 of the best "
        "validation macro-F1) and isotonic calibration.",
        "",
        "## Headline (test set, at each model's threshold)",
        "",
    ]
    rows = []
    for name, m in models.items():
        t, lat = m["test_at_threshold"], m["latency"]
        rows.append(
            [
                name,
                _f(t["macro_f1"]),
                _f(t["macro_f1_attacks_only"]),
                _pct(t["benign_fpr"], 3),
                _pct(t["attack_detection_rate"]),
                _f(t["brier"], 5),
                _f(_macro_pr_auc(m)),
                _f(m["threshold"]),
                _size(m),
                _f(m["training_seconds_final_fit"], 0) + " s",
                _f(lat["single_alert_median_ms"], 2) + " ms",
                f"{lat['batch_rows_per_second']:,}",
            ]
        )
    parts.append(
        _table(
            [
                "Model",
                "Macro-F1",
                "Macro-F1 (attacks)",
                "BENIGN FPR",
                "Attack detection",
                "Brier (cal.)",
                "Mean PR-AUC",
                "Threshold",
                "Size",
                "Train time (final fit)",
                "Latency / alert (median)",
                "Batch rows/s",
            ],
            rows,
        )  # fmt: skip
    )
    parts += [
        "",
        f"Training device: LightGBM on CPU; MLP on `{mlp.get('device', '?')}`. Latency is CPU-only for "
        "both, single row, including preprocessing and calibration for the MLP.",
        "",
        "## Per family (test F1 / recall)",
        "",
    ]
    classes = lgbm["classes"]
    fam_rows = []
    for c in classes:
        a, b = lgbm["test_at_threshold"]["per_family"][c], mlp["test_at_threshold"]["per_family"][c]
        fam_rows.append(
            [c, _f(a["support"]), _f(a["f1"]), _f(b["f1"]), _f(a["recall"]), _f(b["recall"]),
             _f(a["precision"]), _f(b["precision"])]
        )  # fmt: skip
    parts.append(
        _table(
            [
                "Family",
                "Test rows",
                "F1 LGBM",
                "F1 MLP",
                "Recall LGBM",
                "Recall MLP",
                "Precision LGBM",
                "Precision MLP",
            ],
            fam_rows,
        )  # fmt: skip
    )
    parts += ["", "Held-out families (never trained on), share flagged as an attack:", ""]
    ho_rows = []
    for label in sorted(set(lgbm["held_out_families"]) | set(mlp["held_out_families"])):
        a = lgbm["held_out_families"].get(label, {})
        b = mlp["held_out_families"].get(label, {})
        ho_rows.append(
            [label, _f(a.get("rows") or b.get("rows")), _pct(a.get("flagged_as_attack"), 0),
             _pct(b.get("flagged_as_attack"), 0)]
        )  # fmt: skip
    if ho_rows:
        parts.append(_table(["Label", "Rows", "LGBM", "MLP"], ho_rows))

    ablation = mlp.get("ablation_loss") or {}
    if ablation:
        parts += [
            "",
            "## Ablation: MLP loss function (same config, full training set)",
            "",
            "The deployed variant is chosen on validation macro-F1 at threshold; test numbers are "
            "reported for both.",
            "",
        ]
        ab_rows = []
        for name, r in ablation.items():
            t = r["test_at_threshold"]
            label = "cross-entropy" if name == "ce" else f"focal (γ = {r['config']['gamma']})"
            ab_rows.append(
                [
                    label + (" ✓" if r["deployed"] else ""),
                    r["config"]["weights"],
                    _f(r["validation"]["macro_f1_at_threshold"]),
                    _f(t["macro_f1"]),
                    _pct(t["benign_fpr"], 3),
                    _f(r["test_f1_by_family"].get("Bot")),
                    f"{r['best_epoch']}/{r['epochs_run']}",
                    _f(r["training_seconds"], 0) + " s",
                ]
            )
        parts.append(
            _table(
                [
                    "Loss",
                    "Class weights",
                    "Val macro-F1 @thr",
                    "Test macro-F1",
                    "Test BENIGN FPR",
                    "Test Bot F1",
                    "Best / run epochs",
                    "Train time",
                ],
                ab_rows,
            )  # fmt: skip
        )

    grid = (mlp.get("grid") or {}).get("results") or []
    if grid:
        cap = mlp["grid"].get("benign_sample_cap")
        parts += [
            "",
            "## MLP hyperparameter grid (validation macro-F1, argmax)",
            "",
            f"Trained on all attack rows + {cap:,} sampled BENIGN rows."
            if cap
            else "Trained on all rows.",
            "",
        ]
        parts.append(
            _table(
                ["Hidden", "Dropout", "LR", "Weights", "Val macro-F1", "Best epoch", "Time"],
                [
                    [
                        "-".join(map(str, g["hidden"])),
                        _f(g["dropout"], 2),
                        f"{g['lr']:g}",
                        g["weights"],
                        _f(g["val_macro_f1"]),
                        str(g["best_epoch"]),
                        _f(g["seconds"], 0) + " s",
                    ]
                    for g in grid
                ],
            )  # fmt: skip
        )

    if cross_day:
        key = f"at_fpr_{cross_day['setup']['target_benign_fpr']:g}"
        names = {"lgbm": "LightGBM", "mlp": "PyTorch MLP"}
        parts += [
            "",
            "## Cross-day robustness (binary, train Mon–Wed → test Thu–Fri)",
            "",
            "No attack family occurs on both sides of the split, so every Thu–Fri attack is a type "
            "the detector never saw. The threshold gives BENIGN FPR ≤ "
            f"{cross_day['setup']['target_benign_fpr']:.0%} on Mon–Wed validation.",
            "",
        ]
        cd_rows = []
        for m, r in cross_day["models"].items():
            v, u = r["in_period_validation"][key], r["unseen_days"]
            cd_rows.append(
                [names.get(m, m), _pct(v["attack_detection_rate"]), _pct(v["benign_fpr"], 3),
                 _f(u["auroc"]), _pct(u[key]["attack_detection_rate"]), _pct(u[key]["benign_fpr"], 3)]
            )  # fmt: skip
        parts.append(
            _table(
                [
                    "Model",
                    "Mon–Wed detection (seen types)",
                    "Mon–Wed BENIGN FPR",
                    "Thu–Fri AUROC",
                    "Thu–Fri detection (unseen types)",
                    "Thu–Fri BENIGN FPR",
                ],
                cd_rows,
            )  # fmt: skip
        )
        labels = sorted(
            {lab for r in cross_day["models"].values() for lab in r["unseen_days"][key]["by_label"]}
        )
        model_keys = list(cross_day["models"])
        parts += ["", "Unseen attack types, share flagged:", ""]
        parts.append(
            _table(
                ["Label", "Rows", *[names.get(m, m) for m in model_keys]],
                [
                    [
                        lab,
                        _f(
                            next(iter(cross_day["models"].values()))["unseen_days"][key][
                                "by_label"
                            ][lab]["rows"]
                        ),
                    ]
                    + [
                        _pct(
                            cross_day["models"][m]["unseen_days"][key]["by_label"][lab]["flagged"],
                            1,
                        )
                        for m in model_keys
                    ]
                    for lab in labels
                ],
            )
        )
        parts += ["", "![Cross-day detection](figures/cross_day_detection.png)"]

    parts += [
        "",
        "## Figures",
        "",
        "- `figures/lgbm_confusion_matrix.png`, `figures/mlp_confusion_matrix.png`",
        "- `figures/lgbm_pr_curves.png`, `figures/mlp_pr_curves.png`",
        "- `figures/mlp_training_curves.png` (validation log-loss and macro-F1 per epoch, CE vs focal)",
        "",
    ]
    return "\n".join(parts)


def model_card(m: dict[str, Any], meta: dict[str, Any], cross_day: dict[str, Any] | None) -> str:
    is_lgbm = m["model"] == "lightgbm"
    name = "LightGBM baseline" if is_lgbm else "PyTorch MLP"
    t = m["test_at_threshold"]
    if is_lgbm:
        details = [
            f"- **Type:** gradient-boosted trees (LightGBM {meta.get('lightgbm_version', '')}), multiclass.",
            f"- **Hyperparameters:** {json.dumps(m['best_params'])}; {m['best_iteration']} boosting rounds.",
            "- **Files:** `model.txt` (booster), `calibrator.joblib` (isotonic), `meta.json`.",
        ]
    else:
        c = m["config"]
        details = [
            f"- **Type:** feed-forward network, PyTorch {m.get('torch_version', '')}: "
            f"{len(meta['features'])} → {' → '.join(map(str, c['hidden']))} → {len(m['classes'])}, "
            f"BatchNorm + ReLU + Dropout {c['dropout']}; {m['n_parameters']:,} parameters.",
            f"- **Training:** AdamW (weight decay {c['weight_decay']:g}), OneCycle LR peak {c['lr']:g}, "
            f"batch {c['batch_size']}, "
            + (
                f"the full {c['max_epochs']}-epoch schedule, keeping the epoch with the best validation "
                "macro-F1"
                if c.get("patience") is None
                else f"≤ {c['max_epochs']} epochs with early stopping (patience {c['patience']} after "
                "the learning-rate peak) on validation macro-F1"
            )
            + f"; best epoch {m['best_epoch']}. Loss: "
            f"{'cross-entropy' if c['loss'] == 'ce' else 'focal (γ = ' + str(c['gamma']) + ')'} with "
            f"`{c['weights']}` class weights. Device `{m.get('device', '?')}`.",
            "- **Preprocessing:** per-feature `QuantileTransformer` to a normal distribution, fitted on "
            "training rows only (`preprocessor.joblib`).",
            "- **Files:** `model.pt` (state dict + config; load with `weights_only=True`), "
            "`preprocessor.joblib`, `calibrator.joblib`, `meta.json`.",
        ]
    fam_rows = [
        [c, _f(v["support"]), _f(v["precision"]), _f(v["recall"]), _f(v["f1"]), _f(v["pr_auc"])]
        for c, v in t["per_family"].items()
    ]
    ids = [f for f in ("Destination Port", "Protocol") if f in meta["features"]]
    n_flow = len(meta["features"]) - len(ids)
    id_note = f" plus {' and '.join(i.lower() for i in ids)}" if ids else ""
    attacks = {c: v for c, v in t["per_family"].items() if c != "BENIGN"}
    weakest = min(attacks, key=lambda c: attacks[c]["f1"]) if attacks else "BENIGN"
    held = ", ".join(
        f"{label} {r['flagged_as_attack']:.0%} of {r['rows']}"
        for label, r in m["held_out_families"].items()
    )
    cd_line = ""
    if cross_day:
        r = cross_day["models"].get("lgbm" if is_lgbm else "mlp")
        if r:
            key = f"at_fpr_{cross_day['setup']['target_benign_fpr']:g}"
            cd_line = (
                f"- **Unseen attack types:** trained on Mon–Wed only, this architecture flags "
                f"{_pct(r['unseen_days'][key]['attack_detection_rate'], 1)} of Thu–Fri attacks "
                f"(AUROC {_f(r['unseen_days']['auroc'])}) at BENIGN FPR "
                f"{_pct(r['unseen_days'][key]['benign_fpr'], 2)}. Scores on the random split "
                "overstate performance on new attack types. See `reports/model_comparison.md`."
            )
    lines = [
        f"# Model card: {name} (alert-explainer detector)",
        "",
        f"Generated by `uv run ae compare` on {m['generated_at']} from `reports/{'lgbm' if is_lgbm else 'mlp'}_metrics.json`.",
        "",
        "## Model details",
        *details,
        f"- **Classes:** {', '.join(m['classes'])}. Held out of training: {', '.join(meta['held_out_families'])}.",
        f"- **Decision rule:** {meta['decision_rule']}; threshold {m['threshold']:.4f}.",
        f"- **Confidence shown to users:** {meta['confidence']}.",
        f"- **Seed:** {meta['seed']}.",
        "",
        "## Intended use",
        "- Research demonstrator: detect attack families in CIC-IDS2017-style network-flow features and hand "
        "alerts to the explanation layer. The detector decides the label and, with deterministic rules, the "
        "severity; the LLM never does.",
        "- **Not** for production network defence without retraining and validation on the target network.",
        "",
        "## Data",
        f"- CIC-IDS2017 `TrafficLabelling` CSVs, cleaned and de-duplicated (see `docs/data_card.md`). "
        f"Stratified split: {m['rows']['train']:,} train / {m['rows']['val']:,} validation / "
        f"{m['rows']['test']:,} test rows; {m['rows']['held_out']} held-out Other-rare rows.",
        f"- Features: {n_flow} flow statistics{id_note}. No IP addresses, timestamps or flow IDs.",
        "",
        "## Metrics (test set, at the threshold)",
        f"- Macro-F1 **{_f(t['macro_f1'])}** (attacks only {_f(t['macro_f1_attacks_only'])}); "
        f"BENIGN false-positive rate **{_pct(t['benign_fpr'], 3)}**; attack detection rate "
        f"{_pct(t['attack_detection_rate'])}; Brier score {_f(t['brier'], 5)} (calibrated) vs "
        f"{_f(t.get('brier_uncalibrated'), 5)} (raw).",
        f"- Latency (CPU, one alert, median): {_f(m['latency']['single_alert_median_ms'], 2)} ms; "
        f"batch throughput {m['latency']['batch_rows_per_second']:,} rows/s.",
        "",
        _table(["Family", "Test rows", "Precision", "Recall", "F1", "PR-AUC"], fam_rows),
        "",
        "## Limitations",
        "- CIC-IDS2017 has documented labelling and feature-extraction errors (Engelen et al. 2021; "
        "Lanvin et al. 2023). Scores here are on the original labels.",
        "- Lab traffic from one simulated network in 2017. Near-perfect random-split scores partly reflect "
        "how separable this dataset is, not real-world difficulty.",
        f"- {weakest} is the weakest family (test F1 {_f(t['per_family'][weakest]['f1'])})"
        + (
            ": few training flows, and much of its traffic looks like ordinary web requests."
            if weakest == "Bot"
            else "."
        ),
        f"- Held-out rare attacks: {held or 'none'}. The model cannot recognise attack types it has never seen.",
        *([cd_line] if cd_line else []),
        "",
        "## Ethical considerations",
        "- Flow features contain no personal data, but alerts link to IP addresses, which are personal data "
        "under UK GDPR. Those identifiers are pseudonymised before any explanation is generated (Day 10).",
        "- A false positive can trigger an investigation of a person's device. The threshold keeps test "
        f"BENIGN FPR at {_pct(t['benign_fpr'], 3)} (budget {m['target_benign_fpr']:.0%}), and every alert "
        "shows its calibrated confidence.",
        "",
    ]
    return "\n".join(lines)


def write_comparison(models_dir: Path, reports_dir: Path) -> dict[str, Any]:
    lgbm = _load(reports_dir / "lgbm_metrics.json")
    mlp = _load(reports_dir / "mlp_metrics.json")
    if lgbm is None or mlp is None:
        raise FileNotFoundError("Run `ae train-lgbm` and `ae train-mlp` first")
    cross_day = _load(reports_dir / "cross_day.json")

    (reports_dir / "model_comparison.md").write_text(comparison_markdown(lgbm, mlp, cross_day))
    summary_keys = (
        "macro_f1",
        "macro_f1_attacks_only",
        "benign_fpr",
        "attack_detection_rate",
        "brier",
    )
    summary = {
        name: {
            **{k: m["test_at_threshold"][k] for k in summary_keys},
            "threshold": m["threshold"],
            "f1_by_family": {c: v["f1"] for c, v in m["test_at_threshold"]["per_family"].items()},
            "training_seconds_final_fit": m["training_seconds_final_fit"],
            "latency": m["latency"],
        }
        for name, m in (("lgbm", lgbm), ("mlp", mlp))
    }
    if cross_day:
        key = f"at_fpr_{cross_day['setup']['target_benign_fpr']:g}"
        summary["cross_day"] = {
            m: {
                "thu_fri_auroc": r["unseen_days"]["auroc"],
                "thu_fri_detection": r["unseen_days"][key]["attack_detection_rate"],
                "thu_fri_benign_fpr": r["unseen_days"][key]["benign_fpr"],
            }
            for m, r in cross_day["models"].items()
        }
    (reports_dir / "model_comparison.json").write_text(json.dumps(summary, indent=2) + "\n")

    for name, metrics in (("lgbm", lgbm), ("mlp", mlp)):
        meta = _load(models_dir / name / "meta.json")
        if meta is not None:
            (models_dir / name / "model_card.md").write_text(model_card(metrics, meta, cross_day))
    print(f"Wrote {reports_dir / 'model_comparison.md'} and models/*/model_card.md")
    return summary
